#!/usr/bin/env node
// Point the mobile build at ONE environment (qa | production; default qa).
//
//   LT_APP_ENV=production node scripts/app-env.mjs     (or: node scripts/app-env.mjs production)
//
// Run by every `npm run sync:*` before the Portal is built. It writes, for that environment:
//   - MobileApp/.app-env.json            the choice, read by Gradle and capacitor.config.ts
//   - Portal/.env.mobile.local           the Portal's values for `vite build --mode mobile`
//                                        (that file outranks Portal/.env.local in Vite)
//   - ios/App/Config/Environment.xcconfig  bundle id, display name, link host, Google URL scheme
//   - the per-environment Firebase files, copied from the release folder when present
// Nothing it writes is committed. See docs/mobile-release.md "The environment switch".
import fs from 'node:fs';
import path from 'node:path';
import {
  MOBILE_DIR, REPO_DIR, STATE_FILE, describe, loadEnvironments, releaseDir, resolveEnvName,
} from './lib/appEnv.mjs';

const fail = (msg) => { console.error(`app-env: ${msg}`); process.exit(1); };
const note = (msg) => console.log(`app-env: ${msg}`);

/** Parse KEY=VALUE lines (comments and blanks dropped). */
export function parseEnvFile(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

/** The Portal's mobile env: the off-repo file's values, then this environment's on top. */
export function portalEnv(offRepo, web) {
  return { ...offRepo, ...web };
}

/** One plist string value (Apple's XML plist). */
export function plistString(xml, key) {
  const m = new RegExp(`<key>${key}</key>\\s*<string>([^<]*)</string>`).exec(xml);
  return m ? m[1] : null;
}

function main() {
  const config = loadEnvironments();
  let name;
  try { name = resolveEnvName({ explicit: process.argv[2], config }); } catch (e) { fail(e.message); }
  const d = describe(name, config);
  const rel = releaseDir();
  note(`environment = ${name} (${d.appName}, ${d.appId}, https://${d.host})`);

  // 1. The choice, for Gradle / capacitor.config.ts / check-bundle.
  fs.writeFileSync(STATE_FILE, `${JSON.stringify({ env: name, appId: d.appId, appName: d.appName, host: d.host }, null, 2)}\n`);

  // 2. Portal values. The secrets-ish ones (API key, app id, sender id) come from the
  //    off-repo env file when it exists; the environment-defining ones always from
  //    environments.json, so a QA .env.local can never leak into a production bundle.
  const offRepoFile = process.env.LT_MOBILE_ENV_FILE || path.join(rel, 'env', `${name}.env`);
  let offRepo = {};
  if (fs.existsSync(offRepoFile)) {
    offRepo = parseEnvFile(fs.readFileSync(offRepoFile, 'utf8'));
    note(`Portal values from ${offRepoFile}`);
  } else {
    note(`no ${offRepoFile}; Firebase API key / app id fall back to Portal/.env.local`);
  }
  const values = portalEnv(offRepo, d.web);
  const envText = [
    `# GENERATED by MobileApp/scripts/app-env.mjs for LT_APP_ENV=${name}. Do not edit; not committed.`,
    ...Object.entries(values).map(([k, v]) => `${k}=${v}`),
    '',
  ].join('\n');
  fs.writeFileSync(path.join(REPO_DIR, 'Portal', '.env.mobile.local'), envText);

  // 3. iOS.
  const iosApp = path.join(MOBILE_DIR, 'ios', 'App');
  if (fs.existsSync(iosApp)) {
    const plistDest = path.join(iosApp, 'App', 'GoogleService-Info.plist');
    const plistSrc = process.env.LT_IOS_GOOGLE_PLIST || path.join(rel, 'keys', name, 'GoogleService-Info.plist');
    if (fs.existsSync(plistSrc)) { fs.copyFileSync(plistSrc, plistDest); note(`copied ${plistSrc}`); }
    let reversed = 'com.googleusercontent.apps.not-configured';
    if (fs.existsSync(plistDest)) {
      const xml = fs.readFileSync(plistDest, 'utf8');
      const bundle = plistString(xml, 'BUNDLE_ID');
      if (bundle && bundle !== d.appId) {
        fail(`ios/App/App/GoogleService-Info.plist is for ${bundle}, but this build is ${d.appId}. Put the ${name} plist there (or in ${path.join(rel, 'keys', name)}).`);
      }
      reversed = plistString(xml, 'REVERSED_CLIENT_ID') || reversed;
    } else {
      note('no GoogleService-Info.plist: the app builds, Google sign-in will not work until it is added');
    }
    fs.mkdirSync(path.join(iosApp, 'Config'), { recursive: true });
    fs.writeFileSync(path.join(iosApp, 'Config', 'Environment.xcconfig'), [
      `// GENERATED by MobileApp/scripts/app-env.mjs for LT_APP_ENV=${name}. Do not edit; not committed.`,
      `LT_APP_ENV = ${name}`,
      `PRODUCT_BUNDLE_IDENTIFIER = ${d.appId}`,
      `LT_APP_DISPLAY_NAME = ${d.appName}`,
      `LT_LINK_HOST = ${d.host}`,
      `LT_GOOGLE_REVERSED_CLIENT_ID = ${reversed}`,
      '',
    ].join('\n'));
  }

  // 4. Android's Firebase file. CI writes its own before this runs; a local build copies it.
  const gsDest = path.join(MOBILE_DIR, 'android', 'app', 'google-services.json');
  const gsSrc = path.join(rel, 'keys', name, 'google-services.json');
  if (fs.existsSync(gsSrc)) { fs.copyFileSync(gsSrc, gsDest); note(`copied ${gsSrc}`); }
  if (fs.existsSync(gsDest)) {
    const gs = JSON.parse(fs.readFileSync(gsDest, 'utf8'));
    const packages = (gs.client ?? []).map((c) => c?.client_info?.android_client_info?.package_name);
    if (!packages.includes(d.appId)) {
      fail(`android/app/google-services.json has no app ${d.appId} (has: ${packages.join(', ') || 'none'}). Download the file that includes it from Firebase.`);
    }
  } else {
    note('no android/app/google-services.json: the app builds, Google sign-in will not work until it is added');
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
